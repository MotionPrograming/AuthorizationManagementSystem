CREATE TABLE TWO_FACTOR_BACKUP_CODE (
    BACKUP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    CODE_HASH VARCHAR2(128) NOT NULL,
    USED NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    USED_AT TIMESTAMP,
    CONSTRAINT FK_2FA_BACKUP_USER FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID)
);
CREATE INDEX IDX_2FA_BACKUP_USER ON TWO_FACTOR_BACKUP_CODE(USER_ID);
CREATE UNIQUE INDEX UQ_2FA_BACKUP_CODE ON TWO_FACTOR_BACKUP_CODE(USER_ID, CODE_HASH);
